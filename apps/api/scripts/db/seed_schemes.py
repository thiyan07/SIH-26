def seed_real_schemes():
    """Upsert real government schemes into the database."""
    count = 0
    updated = 0
    with session_scope() as s:
        for sc in SCHEMES:
            existing = s.execute(
                select(GovernmentScheme).where(GovernmentScheme.code == sc["code"])
            ).scalars().first()
            if existing is None:
                s.add(GovernmentScheme(**sc))
                count += 1
            else:
                # Update existing scheme with new fields
                for key, value in sc.items():
                    if key != "code":
                        setattr(existing, key, value)
                updated += 1
    print(f"Seeded {count} new schemes, updated {updated} existing schemes.")
    print(f"Total real schemes: {len(SCHEMES)}")


if __name__ == "__main__":
    seed_real_schemes()
