export function tr(key: keyof typeof dict, lang: Language): string {
  return (dict[key] && dict[key][lang]) || dict[key].en
}

export function recommendationLabel(label: string, lang: Language): string {
  if (label === 'GO') return tr('go', lang)
  if (label === 'MODIFY') return tr('modify', lang)
  if (label === 'AVOID') return tr('avoid', lang)
  return label
}

export function interpolate(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, key) => (vars[key] != null ? String(vars[key]) : `{${key}}`))
}

export function schemeDecisionLabel(label: string | undefined | null, lang: Language): string {
  if (!label) return '—'
  if (label.toUpperCase() === 'GO') return tr('schemeDecisionGo', lang)
  if (label.toUpperCase() === 'NO') return tr('schemeDecisionNo', lang)
  if (label.toUpperCase() === 'MODIFY') return tr('schemeDecisionModify', lang)
  if (label === 'no_scheme_selected') return tr('noSchemeCovers', lang)
  if (label === 'no_supported_scheme') return tr('noSupportedScheme', lang)
  if (label.startsWith('scheme:')) return label.replace('scheme:', '') + ' ✓'
  return label
}

